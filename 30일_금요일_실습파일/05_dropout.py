import torch
from torch import nn

# 랜덤 시드를 고정하여 드롭아웃으로 무작위 탈락시킬 때 매번 일관된 결과를 얻도록 합니다.
torch.manual_seed(42)

# 모든 원소가 1.0인 (2행, 4열) 크기의 텐서를 생성합니다.
X = torch.ones(2, 4)

# 드롭아웃 레이어 정의: p=0.5는 학습할 때 뉴런(원소)의 50%를 무작위로 0으로 만들겠다는 의미입니다.
dropout = nn.Dropout(p=0.5)

# --- 1. 학습 모드 (Training Mode) ---
# 학습 모드에서는 지정한 확률(p)에 따라 노드들을 0으로 탈락시킵니다.
# ⚠️ 핵심 원리: 탈락하지 않고 살아남은 값들은 원래 값에 1/(1-p)인 2배를 곱해(스케일링) 균형을 맞춥니다. (1.0 -> 2.0)
dropout.train()
for i in range(3):
    # .tolist()는 텐서 데이터를 우리가 보기 편한 파이썬 리스트 형태로 변환해줍니다.
    print("train", i + 1, dropout(X).tolist())

# Dropout을 평가 모드로 바꾸세요. dropout.eval()은 mode만 바꿉니다.
# 평가 모드의 Dropout은 입력을 그대로 전달하며, gradient 비활성화와는 별개의 기능입니다.
# >>> B06
# TODO B06: 위 요구사항에 맞게 이 블록만 완성합니다.

# --- 2. 평가 모드 (Evaluation Mode) 전환 ---
# 평가/테스트 모드에서는 모델의 모든 자원을 온전히 써야 하므로 드롭아웃을 적용하지 않습니다.
dropout.eval() # dropout.train(mode=False) 이렇게 써도 똑같습니다. 하지만 평가할때는 명확하게 eval로 써주세요!
# <<< B06

# --- 3. 평가 모드에서의 동작 확인 ---
# 평가 모드에서는 노드가 전혀 탈락하지 않으므로 입력했던 1.0이 그대로 통과하여 출력됩니다.
for i in range(3):
    print("eval", i + 1, dropout(X).tolist())

